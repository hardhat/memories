"""Sidecar outputs: memo_ids.h, memo.sym, memo.lst, memo.layout.txt (compiler-spec.md section 8)."""
import json
import re

from .datread import Dat
from .disasm import disassemble, make_syms
from .spec import (ASSET_BASE, BLOCK_CHARS, BLOCK_INDEX, BLOCK_META, BLOCK_VARS, CMP, EXPR_NONE, F_MISSING,
                   MAGIC, MAX_SCENES, NO_TRIGGER, NO_VAR, OP, SCENE_CODE_BASE, SCENE_STR_BASE, T_UNUSED,
                   VERSION)

TYPE_NAMES = {0: "MAGIC", 1: "TILESET", 2: "PALETTE", 3: "SCENE_CODE", 4: "STRINGS", 5: "TILEMAP",
              6: "TABLE", 7: "MAPDEF", 8: "PORTRAIT", 0xFF: "UNUSED"}


def ident(name, strip=""):
    if strip and name.startswith(strip):
        name = name[len(strip):]
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()


def ids_header(p, dat_bytes, scene_codes):
    dat = Dat(dat_bytes)
    out = ["/* Generated by memo_dat.py. Do not edit. */",
           "#ifndef MEMO_IDS_H", "#define MEMO_IDS_H", ""]
    out += [f"#define MEMO_CONTENT_CRC   0x{dat.crc:08X}UL",
            f"#define MEMO_SCENE_COUNT   {len(p.scenes)}",
            f"#define MEMO_MAX_SCENES    {MAX_SCENES}",
            f"#define MEMO_VAR_COUNT     {len(p.var_names)}",
            f"#define CODE_BUF_SIZE      {p.config['limits']['code_buf']}",
            f"#define CALL_DEPTH_MAX     {p.config['limits']['call_depth']}",
            f"#define DIALOG_COLS        {p.config['text']['cols']}",
            f"#define DIALOG_MAX_STRING  128", ""]
    out += ["/* Fixed block ids */",
            f"#define BLOCK_META         {BLOCK_META}", f"#define BLOCK_INDEX        {BLOCK_INDEX}",
            f"#define BLOCK_VARS         {BLOCK_VARS}", f"#define BLOCK_CHARS        {BLOCK_CHARS}",
            f"#define SCENE_CODE_BASE    {SCENE_CODE_BASE}", f"#define SCENE_STR_BASE     {SCENE_STR_BASE}",
            f"#define ASSET_BASE         {ASSET_BASE}", ""]
    out += ["/* Format */",
            f"#define MEMO_MAGIC         0x{MAGIC:08X}UL", f"#define MEMO_FORMAT_VERSION {VERSION}",
            f"#define DAT_TYPE_UNUSED    0x{T_UNUSED:02X}", f"#define DAT_FLAG_MISSING   0x{F_MISSING:02X}",
            f"#define NO_VAR             0x{NO_VAR:02X}", f"#define NO_TRIGGER         0x{NO_TRIGGER:02X}",
            f"#define EXPR_NONE          {EXPR_NONE}"]
    out += [f"#define CMP_{n.upper():<8}   {v}" for n, v in CMP.items()]
    out += [f"#define EXPLORE_TRIGGERS_MAX {p.config['limits']['explore_triggers']}",
            f"#define CHOICE_OPTIONS_MAX {p.config['choice']['options_max']}",
            f"#define CHOICE_LINES_MAX   {p.config['choice']['lines_max']}", ""]
    out += ["/* Opcodes */"] + [f"#define OP_{n:<8} 0x{v:02X}" for n, v in OP.items()] + [""]
    out += ["/* Variables */"] + [f"#define VAR_{ident(n):<24} {i}" for i, n in enumerate(p.var_names)] + [""]
    bits = [b for g in p.bit_groups.values() for b in g]
    out += ["/* Clue bits (in the clues variable) */"] + [f"#define {ident(b):<10} {i}" for i, b in enumerate(bits)] + [""]

    def enum(prefix, names, strip=""):
        lines = [f"#define {prefix}_{ident(n, strip):<22} {i}" for i, n in enumerate(names)]
        return lines + [f"#define {prefix}_COUNT {len(names)}", ""]

    out += ["/* Characters */"] + enum("CHAR", p.char_names)
    out += ["/* Maps */"] + enum("MAP", p.map_names)
    out += ["/* CGs */"] + enum("CG", p.cg_names, "CG-")
    out += ["/* Triggers (global names) */"] + enum("TRIG", p.trigger_names)
    out += ["/* Music */"] + enum("MUSIC", p.music)
    out += ["/* Sound effects */"] + enum("SFX", p.sfx)
    out += ["/* Times of day */"] + enum("TIME", p.times)
    out += ["#endif /* MEMO_IDS_H */", ""]
    return "\n".join(out)


def sym_json(p, scene_codes):
    syms = make_syms(p)
    syms["scenes"] = [{
        "id": sc.scene_id,
        "blocks": sc.labels,
        "choices": sc.choices,
        "strings": sc.strings.where,
    } for sc in scene_codes]
    return json.dumps(syms, indent=1)


def listing(p, scene_codes):
    syms = make_syms(p)
    out = []
    for sc in scene_codes:
        out.append(f"; ===== {sc.scene_id}  entry {sc.entry_pc:04x}  {len(sc.code)} bytes  "
                   f"{len(sc.strings.items)} strings =====")
        out += disassemble(sc.code, syms, sc.strings.items, sc.labels)
        out.append("")
    return "\n".join(out)


def layout_text(p, layout, total):
    lines = ["id    type        offset    size  flags  name", "-" * 52]
    for bid, typ, off, size, flags, name in layout:
        note = "  (missing art)" if flags & F_MISSING else ""
        lines.append(f"{bid:<5} {TYPE_NAMES.get(typ, typ):<10} {off:>8} {size:>7}  0x{flags:02X}   {name}{note}")
    header = min((off for _, _, off, _, _, _ in layout if off), default=0)
    lines += ["", f"total {total} bytes in {len(layout)} blocks (header {header} bytes)"]
    limits = p.config["limits"]
    lines.append(f"code buffer limit {limits['code_buf']} bytes (warn above {limits['code_warn']})")
    return "\n".join(lines) + "\n"
